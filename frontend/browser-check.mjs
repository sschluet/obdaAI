import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
const output='../.local/browser';await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.emulateMedia({reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:18765');
await page.getByLabel('Passwort',{exact:true}).fill('synthetic-ui-password');
await page.getByRole('button',{name:'Anmelden',exact:true}).click();
await page.getByRole('heading',{name:'Womit möchtest du beginnen?'}).waitFor();
await page.screenshot({path:output+'/desktop.png',fullPage:true,animations:'disabled'});
await page.getByLabel('Nachricht',{exact:true}).fill('Synthetic browser question');
await page.getByRole('button',{name:'Nachricht senden',exact:true}).click();
await page.getByText('Antwort abgeschlossen',{exact:true}).waitFor();
if(!await page.getByText('SYNTHETIC_BROWSER_REPLY:',{exact:false}).count())throw Error('Missing persisted reply');
await page.reload();
await page.getByRole('button',{name:'Neues Gespräch',exact:true}).waitFor();
await page.getByRole('button',{name:'Neues Gespräch',exact:true}).count();
// The latest chat must reopen from persisted history after reload.
await page.locator('.history button').first().click();
await page.getByText('SYNTHETIC_BROWSER_REPLY:',{exact:false}).waitFor();
await page.getByRole('button',{name:'Gespräch umbenennen',exact:true}).click();
await page.getByLabel('Titel',{exact:true}).fill('Synthetic browser history');
await page.getByRole('button',{name:'Speichern',exact:true}).click();
await page.getByRole('button',{name:'Synthetic browser history',exact:true}).waitFor();
await page.screenshot({path:output+'/chat.png',fullPage:true,animations:'disabled'});
await page.getByRole('button',{name:'Dunkles Design',exact:true}).click();
await page.screenshot({path:output+'/dark.png',fullPage:true,animations:'disabled'});
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Navigation öffnen',exact:true}).click();
await page.getByRole('button',{name:'Einstellungen',exact:true}).click();
await page.getByRole('heading',{name:'Einstellungen',exact:true}).waitFor();
await page.waitForFunction(()=>document.querySelector('.setting-card').getBoundingClientRect().right <= innerWidth);
if(await page.locator('.page-content').evaluate(e=>e.scrollWidth>e.clientWidth))throw Error('Mobile panel overflow');
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
await page.screenshot({path:output+'/mobile.png',fullPage:true,animations:'disabled'});
await page.getByRole('button',{name:'Navigation öffnen',exact:true}).click();
await page.getByRole('button',{name:'Chat',exact:true}).click();
await page.getByRole('button',{name:'Gespräch löschen',exact:true}).click();
await page.getByRole('button',{name:'Löschen',exact:true}).click();
await page.getByRole('heading',{name:'Womit möchtest du beginnen?'}).waitFor();
await page.getByRole('button',{name:'Navigation öffnen',exact:true}).click();
await page.getByRole('button',{name:'Abmelden',exact:true}).click();
await page.getByRole('heading',{name:'Ein Ort für deine Ideen.',exact:true}).waitFor();
if(errors.length)throw Error(errors.join('\n'));
await browser.close();console.log('Browser checks passed: login, SSE chat, history after reload, rename, dark, mobile, delete, logout. Synthetic provider only.');
